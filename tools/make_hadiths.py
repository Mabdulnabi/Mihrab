#!/usr/bin/env python3
"""Writes web/hadiths.js: a curated set of short sayings of the Prophet, each checked against Sahih al-Bukhari and
Sahih Muslim (Arabic).

    python3 tools/make_hadiths.py <folder with ara-bukhari.min.json and ara-muslim.min.json>

Both books come from the open hadith-api dataset (github.com/fawazahmed0/hadith-api), which keeps their text as it is.
Each entry below has a phrase that must appear in one of the two books; the script stops if it doesn't, and cites the
book and the number the dataset gives. To add one, add a line here and run the script again.
"""
import json
import os
import re
import sys

OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'web', 'hadiths.js')
SOURCES = [('ara-bukhari.min.json', 'البخاري'), ('ara-muslim.min.json', 'مسلم')]

# (what the Prophet said, a phrase from the book to find it by)
HADITHS = [
    ('إنما الأعمال بالنيات', 'إنما الأعمال بالنيات'),
    ('الدين النصيحة', 'الدين النصيحة'),
    ('المسلم من سلم المسلمون من لسانه ويده', 'المسلم من سلم المسلمون من لسانه'),
    ('لا يؤمن أحدكم حتى يحب لأخيه ما يحب لنفسه', 'لا يؤمن أحدكم حتى يحب لأخيه'),
    ('من كان يؤمن بالله واليوم الآخر فليقل خيراً أو ليصمت', 'فليقل خيرا أو ليصمت'),
    ('الكلمة الطيبة صدقة', 'الكلمة الطيبة صدقة'),
    ('الطهور شطر الإيمان', 'الطهور شطر الإيمان'),
    ('خيركم من تعلّم القرآن وعلّمه', 'خيركم من تعلم القرآن وعلمه'),
    ('من سلك طريقاً يلتمس فيه علماً سهّل الله له به طريقاً إلى الجنة', 'من سلك طريقا يلتمس فيه علما'),
    ('الساعي على الأرملة والمسكين كالمجاهد في سبيل الله', 'الساعي على الأرملة والمسكين'),
    ('ليس الشديد بالصُّرعة، إنما الشديد الذي يملك نفسه عند الغضب', 'ليس الشديد بالصرعة'),
    ('كل معروف صدقة', 'كل معروف صدقة'),
    ('من دلّ على خير فله مثل أجر فاعله', 'من دل على خير فله مثل أجر فاعله'),
    ('البرّ حسن الخلق', 'البر حسن الخلق'),
    ('من ستر مسلماً ستره الله في الدنيا والآخرة', 'من ستر مسلما ستره الله'),
    ('إياكم والظن، فإن الظن أكذب الحديث', 'إياكم والظن'),
    ('المؤمن القوي خير وأحب إلى الله من المؤمن الضعيف، وفي كل خير', 'المؤمن القوي خير'),
    ('احرص على ما ينفعك، واستعن بالله ولا تعجز', 'احرص على ما ينفعك'),
    ('من صلّى الصبح فهو في ذمة الله', 'من صلى الصبح فهو في ذمة الله'),
    ('ما نقصت صدقة من مال', 'ما نقصت صدقة من مال'),
    ('يسّروا ولا تعسّروا، وبشّروا ولا تنفّروا', 'يسروا ولا تعسروا'),
    ('ما من مولود إلا يولد على الفطرة', 'ما من مولود إلا يولد على الفطرة'),
]

D = re.compile('[\u064B-\u065F\u0670\u06D6-\u06ED\u200f\u200e\u0640]')


def norm(t):
    """Comparable text: no diacritics or punctuation, the same alef, ya and ta marbuta."""
    t = D.sub('', t)
    t = re.sub(r'[^\u0600-\u06FF\s]', ' ', t)
    t = t.replace('إ', 'ا').replace('أ', 'ا').replace('آ', 'ا').replace('ى', 'ي').replace('ة', 'ه')
    return re.sub(r'\s+', ' ', t)


def main(folder):
    books = []
    for name, label in SOURCES:
        with open(os.path.join(folder, name), encoding='utf-8') as f:
            for h in json.load(f)['hadiths']:
                books.append((label, h['hadithnumber'], norm(h.get('text', ''))))
    lines = ['/* Generated by tools/make_hadiths.py from Sahih al-Bukhari and Sahih Muslim (Arabic). Do not edit by hand. */',
             'var HADITHS = [']
    for text, phrase in HADITHS:
        key = norm(phrase)
        hit = next(((label, n) for label, n, t in books if key in t), None)
        if not hit:
            sys.exit('not found in Bukhari or Muslim: %s' % phrase)
        src = 'صحيح %s، رقم %s' % hit
        lines.append('  {text: %s, src: %s},' % (json.dumps(text, ensure_ascii=False), json.dumps(src, ensure_ascii=False)))
    lines += [']', '']
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines))
    print('wrote %d hadiths to %s' % (len(HADITHS), OUT))


if __name__ == '__main__':
    main(sys.argv[1])
