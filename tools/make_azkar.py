#!/usr/bin/env python3
"""Writes web/azkar.js from the morning and evening remembrances of Hisn al-Muslim (حصن المسلم).

    python3 tools/make_azkar.py <path to adhkar.json>

The file is the open dataset github.com/rn0x/Adhkar-json, whose first section is "أذكار الصباح والمساء" with the
text of Hisn al-Muslim as it is. Each remembrance is cited to its number in that section and how many times to say it.
"""
import json
import os
import re
import sys

OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'web', 'azkar.js')
SECTION = 'أذكار الصباح والمساء'
MAX_LEN = 300


def main(path):
    with open(path, encoding='utf-8') as f:
        sections = json.load(f)
    section = next((s for s in sections if s.get('category') == SECTION), None)
    if section is None:
        sys.exit('section not found: %s' % SECTION)

    items = []
    for entry in section['array']:
        text = re.sub(r'\[[^\]]*\]', '', entry['text'])
        text = text.replace('((', '').replace('))', '')
        text = re.sub(r'\s+', ' ', text).strip()
        if not text or len(text) > MAX_LEN:
            continue
        count = entry.get('count', '')
        src = 'حصن المسلم، رقم %s' % entry['id']
        if count and str(count) != '1':
            src += '، تكرار %s مرات' % count
        items.append((text, src))

    lines = ['/* Generated by tools/make_azkar.py from Hisn al-Muslim (morning and evening). Do not edit by hand. */',
             'var AZKAR = [']
    for text, src in items:
        lines.append('  {text: %s, src: %s},' % (json.dumps(text, ensure_ascii=False), json.dumps(src, ensure_ascii=False)))
    lines += [']', '']
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines))
    print('wrote %d remembrances to %s' % (len(items), OUT))


if __name__ == '__main__':
    main(sys.argv[1])
